/**
 * Converts the original MEF CSV files in data/ into compact, lossless TypeScript modules in
 * src/generated/ (git-ignored). Run automatically by `npm run build` and `npm test`.
 *
 * Yearly update: replace the four CSV files in data/ (keep the original MEF names, e.g.
 * CambodiaProvinceList2026.csv) and delete the old-year files. The year is detected from the
 * file names, nothing else needs editing.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCsv } from './csv.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = path.join(root, 'data');
const outDir = path.join(root, 'src', 'generated');

const SPECS = [
  { key: 'provinces', level: 'province', prefix: 'CambodiaProvinceList', parents: [] },
  { key: 'districts', level: 'district', prefix: 'CambodiaDistrictList', parents: ['province_code'] },
  {
    key: 'communes',
    level: 'commune',
    prefix: 'CambodiaCommuneList',
    parents: ['province_code', 'district_code'],
  },
  {
    key: 'villages',
    level: 'village',
    prefix: 'CambodiaVillagesList',
    parents: ['province_code', 'district_code', 'commune_code'],
  },
];

function fail(message) {
  console.error(`build-data: ${message}`);
  process.exit(1);
}

const files = readdirSync(dataDir);
const years = new Set();
const chosen = [];

for (const spec of SPECS) {
  const re = new RegExp(`^${spec.prefix}(\\d{4})\\.csv$`);
  const matches = files.map((f) => ({ f, m: re.exec(f) })).filter((x) => x.m);
  if (matches.length === 0) fail(`no file named ${spec.prefix}<year>.csv found in data/`);
  if (matches.length > 1) {
    fail(`several files for ${spec.prefix}: ${matches.map((x) => x.f).join(', ')}. Delete the old-year file(s).`);
  }
  years.add(matches[0].m[1]);
  chosen.push({ ...spec, file: matches[0].f });
}
if (years.size !== 1) fail(`the four CSV files must have the same year, found: ${[...years].join(', ')}`);
const dataYear = Number([...years][0]);

mkdirSync(outDir, { recursive: true });

const counts = {};
for (const spec of chosen) {
  const { header, records } = parseCsv(readFileSync(path.join(dataDir, spec.file), 'utf8'));
  const own = [`${spec.level}_code`, `${spec.level}_kh`, `${spec.level}_en`];
  const missing = [...own, ...spec.parents].filter((c) => !header.includes(c));
  if (missing.length > 0) fail(`${spec.file} is missing column(s): ${missing.join(', ')}`);

  // Row layout: [code, nameKh, nameEn, ...parent codes]. CSV row order is preserved exactly.
  const rows = [];
  for (const rec of records) {
    const cell = (c) => (rec[c] ?? '').trim();
    const code = cell(own[0]);
    if (!code) continue; // skip blank / malformed lines
    rows.push([code, cell(own[1]), cell(own[2]), ...spec.parents.map(cell)]);
  }
  counts[spec.key] = rows.length;

  // The data is stored as one JSON string and parsed lazily on first use (fast + compact).
  const literal = JSON.stringify(JSON.stringify(rows));
  const source =
    `// AUTO-GENERATED by scripts/build-data.mjs from data/${spec.file}. Do not edit.\n` +
    `export default function load(): string[][] {\n  return JSON.parse(${literal}) as string[][];\n}\n`;
  writeFileSync(path.join(outDir, `${spec.key}.ts`), source);
}

const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
writeFileSync(
  path.join(outDir, 'meta.ts'),
  `// AUTO-GENERATED by scripts/build-data.mjs. Do not edit.\n` +
    `export const DATA_YEAR = ${dataYear};\nexport const VERSION = ${JSON.stringify(pkg.version)};\n`,
);

console.log(
  `build-data: ${dataYear} data -> ` + Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', '),
);
